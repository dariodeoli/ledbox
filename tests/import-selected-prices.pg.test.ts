import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { test } from "node:test";
test("selective prices: signed preview CAS, atomic receipts, tenant, replay, preserved fields and report recovery", { skip: !process.env.TEST_DATABASE_URL }, async () => {
    const url = new URL(process.env.TEST_DATABASE_URL!);
    assert.ok(["localhost", "127.0.0.1"].includes(url.hostname));
    process.env.DATABASE_URL = url.toString();
    process.env.AUTH_SECRET ||= "selective-price-local-fixture-secret";
    const { db } = await import("../lib/server/db");
    const { portalAuditContext } = await import("../lib/server/audit");
    const { previewSelectedPrices, applySelectedPrices, selectedPriceReport } = await import("../lib/server/import-selected-prices");
    const org = randomUUID(), other = randomUUID();
    await db.organization.createMany({ data: [org, other].map(id => ({ id, slug: `selected-${id}`, name: "Selective fixture" })) });
    const ctx = portalAuditContext(org, "Selective fixture");
    const request = new Request("http://localhost/api/admin/import/productos");
    try {
        const item = await db.inventoryItem.create({ data: { id: randomUUID(), organizationId: org, sku: "A", name: "Original", category: "Sillas", listPrice: 10000, wholesalePrice: 7000, minimumPrice: 1000, quantity: 0, notes: "Original notes", imageData: new Uint8Array([1]), imageMime: "image/webp", catalogAudience: "HIDDEN" } });
        const foreign = await db.inventoryItem.create({ data: { id: randomUUID(), organizationId: other, sku: "A", name: "Foreign", category: "Other", listPrice: 999, quantity: 0 } });
        const wholesaleTier = await db.inventoryPriceTier.create({ data: { id: randomUUID(), organizationId: org, inventoryId: item.id, audience: "WHOLESALE", fromDays: 5, mode: "TOTAL", price: 20000 } });
        const input = { productos: [{ codigo: "A", cambios: { listPrice: { op: "REPLACE", value: 12000 }, tarifasFinal: { op: "REPLACE", value: [{ fromDays: 3, mode: "TOTAL", price: 25000 }] } } }] };
        const inspect = async (raw: unknown, context = ctx) => { const response = await previewSelectedPrices(context, raw); assert.equal(response.status, 200); return response.json(); };
        const preview = await inspect(input);
        assert.equal(preview.filas[0].cambios[0].antes, 10000);
        assert.equal(preview.filas[0].cambios[0].despues, 12000);
        assert.equal(await db.idempotencyKey.count({ where: { organizationId: org } }), 0, "preview has no writes");
        const original = await db.inventoryItem.findUniqueOrThrow({ where: { id: item.id } });
        await db.inventoryItem.update({ where: { id: item.id }, data: { notes: "Concurrent unrelated edit", wholesalePrice: 8000 } });
        const lote = randomUUID();
        const first = await applySelectedPrices(ctx, input, preview.confirmationToken, lote, request);
        assert.equal(first.status, 200);
        const applied = await first.json();
        assert.equal(applied.filasPrecio[0].estado, "aplicada");
        const after = await db.inventoryItem.findUniqueOrThrow({ where: { id: item.id } });
        const { listPrice: _p, notes: _n, updatedAt: _u, ...rest } = after;
        const { listPrice: _op, notes: _on, updatedAt: _ou, ...restOriginal } = original;
        assert.deepEqual(rest, { ...restOriginal, wholesalePrice: 8000 });
        assert.equal(after.listPrice, 12000);
        assert.equal(after.notes, "Concurrent unrelated edit");
        assert.deepEqual(await db.inventoryPriceTier.findUniqueOrThrow({ where: { id: wholesaleTier.id } }), wholesaleTier);
        assert.equal((await db.inventoryItem.findUniqueOrThrow({ where: { id: foreign.id } })).listPrice, 999);
        const auditCount = await db.auditLog.count({ where: { organizationId: org, entityId: item.id } });
        const duplicate = await applySelectedPrices(ctx, input, "expired-or-lost-token", lote, request);
        assert.equal(duplicate.status, 200);
        assert.equal((await duplicate.json()).filasPrecio[0].estado, "aplicada");
        assert.equal(await db.auditLog.count({ where: { organizationId: org, entityId: item.id } }), auditCount);
        assert.deepEqual(await (await selectedPriceReport(org, lote)).json(), applied);
        assert.equal((await selectedPriceReport(other, lote)).status, 404);
        assert.equal((await applySelectedPrices(ctx, { productos: [{ codigo: "A", cambios: { listPrice: { op: "CLEAR" } } }] }, preview.confirmationToken, lote, request)).status, 409);
        const stale = await inspect(input);
        await db.inventoryItem.update({ where: { id: item.id }, data: { listPrice: 14000 } });
        const conflict = await (await applySelectedPrices(ctx, input, stale.confirmationToken, randomUUID(), request)).json();
        assert.equal(conflict.filasPrecio[0].estado, "conflicto");
        assert.equal((await db.inventoryItem.findUniqueOrThrow({ where: { id: item.id } })).listPrice, 14000);
        assert.equal(conflict.reintento.productos.length, 1);
        assert.equal((await applySelectedPrices(portalAuditContext(other, "Foreign"), input, stale.confirmationToken, randomUUID(), request)).status, 409);
        assert.equal((await applySelectedPrices(ctx, input, stale.confirmationToken + "x", randomUUID(), request)).status, 409);
        const { decodeJwt, SignJWT } = await import("jose");
        const expired = await new SignJWT(decodeJwt(stale.confirmationToken)).setProtectedHeader({ alg: "HS256" }).setExpirationTime(1).sign(new TextEncoder().encode(process.env.JWT_SECRET || process.env.AUTH_SECRET!));
        assert.equal((await applySelectedPrices(ctx, input, expired, randomUUID(), request)).status, 409);
        const wholesaleOnly = { productos: [{ codigo: "A", cambios: { wholesalePrice: { op: "REPLACE", value: 5000 }, minimumPrice: { op: "CLEAR" } } }] };
        const wp = await inspect(wholesaleOnly);
        const wr = await (await applySelectedPrices(ctx, wholesaleOnly, wp.confirmationToken, randomUUID(), request)).json();
        assert.equal(wr.filasPrecio[0].estado, "aplicada");
        const wi = await db.inventoryItem.findUniqueOrThrow({ where: { id: item.id } });
        assert.equal(wi.wholesalePrice, 5000);
        assert.equal(wi.minimumPrice, 0);
        assert.equal(wi.listPrice, 14000);
        const clear = { productos: [{ codigo: "A", cambios: { listPrice: { op: "CLEAR" }, tarifasFinal: { op: "CLEAR" } } }] };
        const cp = await inspect(clear), parallelLote = randomUUID();
        const parallel = await Promise.all([applySelectedPrices(ctx, clear, cp.confirmationToken, parallelLote, request), applySelectedPrices(ctx, clear, cp.confirmationToken, parallelLote, request)]);
        assert.ok(parallel.every(r => r.status === 200));
        assert.equal((await db.inventoryItem.findUniqueOrThrow({ where: { id: item.id } })).listPrice, 0);
        assert.equal(await db.inventoryPriceTier.count({ where: { organizationId: org, audience: "RETAIL" } }), 0);
        assert.ok(await db.inventoryPriceTier.findUnique({ where: { id: wholesaleTier.id } }));
        assert.equal(await db.idempotencyKey.count({ where: { organizationId: org, scope: "import:selected-prices:row:v1", key: `${parallelLote}:1` } }), 1);
        // Failure after business writes but before transaction commit rolls back both prices and receipt.
        const rollbackInput = { productos: [{ codigo: "A", cambios: { listPrice: { op: "REPLACE", value: 33000 } } }] };
        const rp = await inspect(rollbackInput), rollbackLote = randomUUID();
        const rollbackAuditCount = await db.auditLog.count({ where: { organizationId: org } });
        const originalTransaction = db.$transaction.bind(db);
        let transactions = 0;
        (db as any).$transaction = (cb: any, options: any) => originalTransaction(async (tx: any) => { const result = await cb(tx); if (++transactions === 2)
            throw new Error("fixture commit interruption"); return result; }, options);
        try {
            await assert.rejects(applySelectedPrices(ctx, rollbackInput, rp.confirmationToken, rollbackLote, request), /fixture commit interruption/);
        }
        finally {
            (db as any).$transaction = originalTransaction;
        }
        assert.equal((await db.inventoryItem.findUniqueOrThrow({ where: { id: item.id } })).listPrice, 0);
        assert.equal(await db.idempotencyKey.count({ where: { organizationId: org, scope: "import:selected-prices:row:v1", key: `${rollbackLote}:1` } }), 0);
        assert.equal(await db.auditLog.count({ where: { organizationId: org } }), rollbackAuditCount);
        assert.equal((await (await selectedPriceReport(org, rollbackLote)).json()).filasPrecio[0].estado, "pendiente");
        const resumed = await (await applySelectedPrices(ctx, rollbackInput, rp.confirmationToken, rollbackLote, request)).json();
        assert.equal(resumed.filasPrecio[0].estado, "aplicada");
        assert.equal((await db.inventoryItem.findUniqueOrThrow({ where: { id: item.id } })).listPrice, 33000);
        const family = await db.inventoryFamily.create({ data: { id: randomUUID(), organizationId: org, code: "F", name: "Fixture family", axes: [] } });
        const variants = await Promise.all(["V1", "V2"].map(sku => db.inventoryItem.create({ data: { id: randomUUID(), organizationId: org, familyId: family.id, variantKey: sku, sku, name: sku, category: "Sillas", quantity: 0, listPrice: 1000 } })));
        const variantInput = { productos: [{ codigo: "V1", cambios: { listPrice: { op: "REPLACE", value: 1500 } } }] };
        const vp = await inspect(variantInput);
        assert.match(vp.filas[0].detalle, /precio propio/);
        const vr = await (await applySelectedPrices(ctx, variantInput, vp.confirmationToken, randomUUID(), request)).json();
        assert.equal(vr.filasPrecio[0].estado, "aplicada");
        const own = await db.inventoryItem.findUniqueOrThrow({ where: { id: variants[0].id } }), sibling = await db.inventoryItem.findUniqueOrThrow({ where: { id: variants[1].id } });
        assert.equal(own.variantOwnPrice, true);
        assert.equal(own.listPrice, 1500);
        assert.equal(sibling.variantOwnPrice, false);
        assert.equal(sibling.listPrice, 1000);
        const variantAudit = await db.auditLog.findFirstOrThrow({ where: { organizationId: org, entityId: own.id } });
        assert.deepEqual((variantAudit.detail as any).changes.variantOwnPrice, { from: false, to: true });
        const sameVariant = { productos: [{ codigo: "V2", cambios: { listPrice: { op: "REPLACE", value: 1000 } } }] };
        const svp = await inspect(sameVariant); assert.ok(!svp.filas[0].detalle.includes("pasa a precio propio"));
        const svr = await (await applySelectedPrices(ctx, sameVariant, svp.confirmationToken, randomUUID(), request)).json(); assert.equal(svr.filasPrecio[0].estado, "conservada");
        assert.equal((await db.inventoryItem.findUniqueOrThrow({ where: { id: variants[1].id } })).variantOwnPrice, false);
        const bad = { productos: [{ codigo: "MISSING", cambios: { listPrice: { op: "CLEAR" } } }, { codigo: "A", cambios: { cantidad: { op: "CLEAR" } } }] };
        const bp = await inspect(bad);
        const br = await (await applySelectedPrices(ctx, bad, bp.confirmationToken, randomUUID(), request)).json();
        assert.ok(br.filasPrecio.every((r: any) => r.estado === "invalida"));
        assert.equal(await db.inventoryItem.count({ where: { organizationId: org } }), 3);
    }
    finally {
        await db.organization.deleteMany({ where: { id: { in: [org, other] } } });
        await db.$disconnect();
    }
});
